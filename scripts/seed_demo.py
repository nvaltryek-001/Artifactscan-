"""Fill a running ArtifactScan server with clearly-labelled demo data.

Every image is a synthetic render from scripts/make_sample_images.py, and
every record says so in its provenance field. Use it to explore the UI or to
record screenshots — never mix it into a real collection database.

    python scripts/seed_demo.py --url http://127.0.0.1:8000 [--reconstruct]
"""
from __future__ import annotations

import argparse
import importlib.util
import io
import time
from pathlib import Path

import numpy as np
import requests
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
_spec = importlib.util.spec_from_file_location("mk", ROOT / "scripts" / "make_sample_images.py")
mk = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(mk)

DEMO = "Demo data — synthetic render generated by scripts/make_sample_images.py. Not a real object."

PLINTH = ("box", (np.array([-1.6, -1.6, -0.25]), np.array([1.6, 1.6, 0.0])), "stone", 1)
SCENES = {
    "turntable": mk.build_scene(),
    "orb": [PLINTH, ("box", (np.array([-0.4, -0.4, 0]), np.array([0.4, 0.4, 0.3])), "bronze", 2),
            ("sphere", (np.array([0, 0, 0.95]), 0.65), "lapis", 3)],
    "stele": [PLINTH, ("box", (np.array([-0.55, -0.18, 0]), np.array([0.55, 0.18, 1.9])), "stone", 8),
              ("box", (np.array([-0.75, -0.3, 0]), np.array([0.75, 0.3, 0.2])), "bronze", 9)],
    "weights": [PLINTH] + [("box", (np.array([x - s, -s, 0]), np.array([x + s, s, 2 * s])), "bronze", 10 + i)
                           for i, (x, s) in enumerate([(-1.0, 0.18), (-0.45, 0.24), (0.2, 0.3), (0.95, 0.38)])],
    "tile": [("box", (np.array([-1.2, -0.9, -0.1]), np.array([1.2, 0.9, 0.0])), "terracotta", 20),
             ("box", (np.array([-0.9, -0.6, 0.0]), np.array([0.9, 0.6, 0.06])), "lapis", 21)],
}

ARTIFACTS = [
    dict(scene="turntable", views=24, title="Terracotta vessel on bronze plinth", category="Ceramics",
         period="Demo object", material="Terracotta, bronze", origin="Synthetic studio scene", dimensions="H ~2.0 units",
         description="Globular vessel with lapis finial on a stepped bronze plinth, "
                     "photographed in a 24-view turntable sequence."),
    dict(scene="orb", views=4, title="Lapis-glazed ritual orb", category="Decorative arts", period="Demo object",
         material="Glazed ceramic", description="Spherical glazed object on a low bronze stand."),
    dict(scene="stele", views=4, title="Carved limestone stele", category="Sculpture", period="Demo object",
         material="Limestone", dimensions="H ~1.9 units", description="Upright stone slab on a bronze base."),
    dict(scene="weights", views=4, title="Graduated bronze weight set", category="Metalwork", period="Demo object",
         material="Bronze", description="Four cubic weights in increasing size."),
    dict(scene="tile", views=3, title="Glazed architectural tile", category="Architecture", period="Demo object",
         material="Terracotta, glaze", description="Rectangular tile with raised glazed panel."),
    dict(scene=None, views=0, title="Inscribed ceremonial tablet", category="Epigraphy", period="Demo object",
         material="Stone", description="Record created ahead of photography."),
]


def render_views(scene, n, w=800, h=600, elev_deg=28):
    focal = 1.2 * max(w, h)
    target = np.array([0.0, 0.0, 0.75])
    out = []
    for k in range(n):
        a = 2 * np.pi * k / n + (0.0 if n > 8 else 0.7)
        elev = np.deg2rad(elev_deg + (8 * np.sin(2 * a) if n > 8 else 0))
        eye = target + 4.4 * np.array([np.cos(a) * np.cos(elev), np.sin(a) * np.cos(elev), np.sin(elev)])
        buf = io.BytesIO()
        Image.fromarray(mk.render(eye, target, w, h, focal, scene)).save(buf, "JPEG", quality=92)
        out.append((f"view_{k:03d}.jpg", buf.getvalue()))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--url", default="http://127.0.0.1:8000")
    ap.add_argument("--reconstruct", action="store_true", help="reconstruct the 24-view turntable artifact")
    ap.add_argument("--skip", action="append", default=[], choices=sorted(SCENES), help="scene(s) to leave out")
    args = ap.parse_args()
    s = requests.Session()
    s.trust_env = False
    turntable_id = None
    for spec in ARTIFACTS:
        spec = dict(spec)
        scene, views = spec.pop("scene"), spec.pop("views")
        if scene in args.skip:
            continue
        r = s.post(f"{args.url}/api/artifacts", json={**spec, "provenance": DEMO, "rights": "CC0 (synthetic demo image)"})
        r.raise_for_status()
        aid = r.json()["id"]
        print("created", spec["title"], aid)
        if scene:
            files = [("files", (name, data, "image/jpeg")) for name, data in render_views(SCENES[scene], views)]
            s.post(f"{args.url}/api/artifacts/{aid}/images", files=files).raise_for_status()
            print(f"  uploaded {views} renders")
        if scene == "turntable":
            turntable_id = aid
    if args.reconstruct and turntable_id:
        job = s.post(f"{args.url}/api/artifacts/{turntable_id}/reconstructions", json={"engine": "auto"}).json()
        print("reconstruction job", job)
        while True:
            j = s.get(f"{args.url}/api/jobs/{job['job_id']}").json()
            print(f"  {j['status']:<10} {j['stage']:<18} {j['message'][:90]}")
            if j["status"] in ("completed", "failed"):
                break
            time.sleep(3)


if __name__ == "__main__":
    main()
